#ifndef __OTA_LAYOUT_H
#define __OTA_LAYOUT_H

#include "stm32f10x.h"

/* ==========================================================================
 * A 区 App 与 B 区 BootLoader 的接口契约
 * ==========================================================================
 *
 * 这个文件虽然放在 B 区目录下，但它**不属于 B 区** —— 它是两个工程共用的
 * 约定文件。之所以放这儿，是因为 A 区工程反正要引用同一目录下的
 * 4G.c / W25Q64.c / m24c02.c，include path 已经指到这里，零额外配置。
 *
 * 为什么必须有这个文件：
 *   升级流程被两个程序接力完成 ——
 *     A 区 App：把新固件写进 W25Q64，然后在 AT24C02 里打上升级标志
 *     B 区 BootLoader：读到标志，把 W25Q64 里的固件搬进 A 区
 *   两个程序是分别编译、分别烧录的，它们之间**没有函数调用**，
 *   唯一的联系就是下面定义的内存布局。布局对不上，表现是
 *   "标志写了，但重启后 BootLoader 没反应" —— 而且不报任何错。
 *
 * 改动纪律：
 *   改这个文件 = 改双方的约定。必须两个工程一起重编、一起烧。
 *   只烧一边，BootLoader 就可能读不懂 A 区写的标志。
 *
 * 什么**不在**这里（留在 B 区自己的 User/main.h）：
 *   - Flash 分区宏 MyFlash_*      —— 只有 BootLoader 关心内部 Flash 怎么分
 *   - BootStaFlag / IAP_* 等运行期标志 —— 只是 BootLoader 命令行内部的状态
 *
 * 编码：UTF-8 带 BOM。ARMCC5 按系统 ANSI 代码页解码源文件，
 *       无 BOM 时中文会被误解析并报 #870-D，务必保留 BOM。
 */

/* --------------------------------------------------------------------------
 * AT24C02 里的升级标志值
 * -------------------------------------------------------------------------- */
/* OTA_Flag 等于这个值，就表示"W25Q64 里有新固件等着搬进 A 区"。
 * 特意用了一个不规整的魔数而不是 1：
 * EEPROM 是掉电保持的，第一次上电时里面可能是随机残留，
 * 用 1 这种常见值有被误判成升级请求的风险，那会让设备去搬一段垃圾数据。 */
#define OTA_SET_FLAG			0x0a050301

/* --------------------------------------------------------------------------
 * OTA 下载缓冲使用的 W25Q64 块号
 * -------------------------------------------------------------------------- */
/* W25Q64 共 8MB，按 64KB 分块。
 *   块 0     —— 固定给 OTA 用（A 区下载的新固件写在这里）
 *   块 1~9   —— 留给"多版本固件"用法（串口 Xmodem 路径，按版本各占一块）
 * 分开是为了让 OTA 下载不会覆盖掉那些存好的版本。 */
#define OTA_W25Q64_BLOCK		0

/* --------------------------------------------------------------------------
 * AT24C02 里保存的结构体
 * -------------------------------------------------------------------------- */
/* AT24C02 容量 256 字节（2Kbit），一页 8 字节。
 * 本结构体 4 + 44 + 32 = 80 字节，无填充（成员都自然对齐），正好 10 页。
 *
 * 注意：成员顺序和类型都改不得 —— 换了顺序，BootLoader 就会把
 *       版本号当成固件长度来读。真要改，两个工程必须同时改、同时烧。 */
typedef struct
{
	uint32_t OTA_Flag;		/* == OTA_SET_FLAG 时，表示需要把 W25Q64 的固件搬进 A 区 */

	uint32_t FileLen[11];	/* 各 W25Q64 块里固件的长度，**下标就是块号**。
	                         * OTA 路径固定用下标 OTA_W25Q64_BLOCK，即 FileLen[0]。
	                         * 数组开 11 个是为了覆盖块 0~9 加一个余量。 */

	uint8_t  OTA_Ver[32];	/* 版本号字符串，失败时用来对照，不参与判断逻辑 */
}OTA_InfoCB;

#define OTA_INFOCB_SIZE			sizeof(OTA_InfoCB)

/* A 区和 B 区各自持有一个实例（两个程序是两个独立的可执行体）。
 * 契约是上面的**结构体布局**，不是这个变量本身 —— 所以两边都声明，
 * 各自由自己的 main.c 定义。 */
extern OTA_InfoCB OTA_Info;

#endif
